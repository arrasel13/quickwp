const CACHE_KEY = "nexora.language";

// The backend's setting is the truth; this cache only saves the first paint
// from flashing English before the settings arrive.
let current: string = (() => {
  try {
    return localStorage.getItem(CACHE_KEY) ?? "en";
  } catch {
    return "en";
  }
})();

const listeners = new Set<() => void>();
const subscribe = (l: () => void) => {
  listeners.add(l);
  return () => listeners.delete(l);
};

export function setLanguage(code: string) {
  if (code === current) return;
  current = code;
  try {
    localStorage.setItem(CACHE_KEY, code);
  } catch {
    // Only the next launch's first paint is affected.
  }
  document.documentElement.lang = code;
  listeners.forEach((l) => l());
}

export function useLanguage() {
  return useSyncExternalStore(subscribe, () => current);
}

/** `t("tldHint", { example: "name.test" })` */
export function useT() {
  const lang = useLanguage();
  return useCallback(
    (key: TKey | string, vars?: Record<string, string>) => {
      let s: string =
        translations[lang]?.[key as TKey] ?? (en as Record<string, string>)[key] ?? key;
      for (const [k, v] of Object.entries(vars ?? {})) s = s.replace(`{${k}}`, v);
      return s;
    },
    [lang],
  );
}
